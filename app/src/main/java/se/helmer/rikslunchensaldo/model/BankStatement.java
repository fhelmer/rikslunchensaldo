package se.helmer.rikslunchensaldo.model;

import android.os.Bundle;

import java.math.BigDecimal;
import java.util.Date;

import com.j256.ormlite.field.DatabaseField;
import com.j256.ormlite.table.DatabaseTable;
import com.tojc.ormlite.android.annotation.AdditionalAnnotation;

import se.helmer.rikslunchensaldo.Utils;

@DatabaseTable(tableName=Contract.BankStatement.TABLE_NAME)
@AdditionalAnnotation.DefaultContentUri(authority=Contract.BankStatement.AUTHORITY, path=Contract.BankStatement.CONTENT_URI_PATH)
@AdditionalAnnotation.DefaultContentMimeTypeVnd(name=Contract.BankStatement.MIMETYPE_NAME, type=Contract.BankStatement.MIMETYPE_TYPE)
public class BankStatement {

    // id is generated by the database and set on the object automagically
    @DatabaseField(generatedId = true)
    private int _id;
    @DatabaseField
    private String description;  // Notes made by user
    @DatabaseField
    private String message;     // Info from Rikslunchen
    @DatabaseField
    private BigDecimal balance;
    @DatabaseField
    private Date date;  // Date should be stored in UTC
    @DatabaseField
    private BigDecimal amount;

    public BankStatement() {

    }
    public BankStatement(String message, BigDecimal amount, BigDecimal balance) {
        this.message = message;
        Date now = new Date();
        this.date = Utils.LocalToGmt(now);
        this.amount = amount;
        this.balance = balance;
    }

    public BigDecimal getBalance() {
        return balance;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public Date getDate() { return date; }

    public int getId() {
        return _id;
    }

    public void updateTimestamp() {
        this.date = Utils.LocalToGmt(new Date());
    }

    public void setValues(Bundle b) {
        String bDescription = b.getString(Contract.BankStatement.DESCRIPTION);
        if (bDescription != null) {
            description = bDescription;
        }

        String bAmount = b.getString(Contract.BankStatement.AMOUNT);
        if (bAmount != null) {
            amount = new BigDecimal(bAmount);
        }

        String bBalance = b.getString(Contract.BankStatement.BALANCE);
        if (bBalance != null) {
            balance = new BigDecimal(bBalance);
        }
    }

    public String toString() {
        return "Amount:" + amount + ", Balance:" +  balance;
    }
}
