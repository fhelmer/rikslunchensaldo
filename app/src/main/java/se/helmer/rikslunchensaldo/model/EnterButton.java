package se.helmer.rikslunchensaldo.model;

import java.math.BigDecimal;
import java.util.Date;

import com.j256.ormlite.field.DatabaseField;
import com.j256.ormlite.table.DatabaseTable;
import com.tojc.ormlite.android.annotation.AdditionalAnnotation;

@DatabaseTable(tableName = Contract.EnterButton.TABLE_NAME)
@AdditionalAnnotation.DefaultContentUri(authority=Contract.EnterButton.AUTHORITY, path=Contract.EnterButton.CONTENT_URI_PATH)
@AdditionalAnnotation.DefaultContentMimeTypeVnd(name=Contract.EnterButton.MIMETYPE_NAME, type=Contract.EnterButton.MIMETYPE_TYPE)

public class EnterButton {

    // id is generated by the database and set on the object automagically
    @DatabaseField(generatedId = true)
    private int _id;
    @DatabaseField
    private String description;
    @DatabaseField
    private BigDecimal amount;

    public String getDescription() {
        return description;
    }

    public String getAmount() {
        return amount.toString();
    }

    public EnterButton() {
    }

    public EnterButton(String description, BigDecimal amount) {
        this.description = description;
        this.amount = amount;
    }
}
