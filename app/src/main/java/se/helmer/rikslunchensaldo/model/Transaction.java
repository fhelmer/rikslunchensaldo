package se.helmer.rikslunchensaldo.model;

import java.math.BigDecimal;
import java.util.Date;

import com.j256.ormlite.field.DataType;
import com.j256.ormlite.field.DatabaseField;
import com.j256.ormlite.table.DatabaseTable;
import com.tojc.ormlite.android.annotation.AdditionalAnnotation;

import se.helmer.rikslunchensaldo.Utils;

@DatabaseTable(tableName = Contract.Transaction.TABLE_NAME)
@AdditionalAnnotation.DefaultContentUri(authority=Contract.AUTHORITY, path=Contract.Transaction.CONTENT_URI_PATH)
@AdditionalAnnotation.DefaultContentMimeTypeVnd(name=Contract.Transaction.MIMETYPE_NAME, type=Contract.Transaction.MIMETYPE_TYPE)
public class Transaction {

    // id is generated by the database and set on the object automagically
    @DatabaseField(generatedId = true)
    private int _id;
    @DatabaseField
    private String description;
    @DatabaseField
    private BigDecimal balance;
    @DatabaseField
    private Date date;  // Date should be stored in UTC
    @DatabaseField
    private BigDecimal amount;

    public Transaction() {

    }
    public Transaction(String description, BigDecimal amount, BigDecimal balance) {
        this.description = description;
        Date now = new Date();
        this.date = Utils.LocalToGmt(now);
        this.amount = amount;
        this.balance = balance;
    }

    public BigDecimal getBalance() {
        return balance;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public Date getDate() { return date; }

    public int getId() {
        return _id;
    }

    public void updateTimestamp() {
        this.date = Utils.LocalToGmt(new Date());
    }
}
